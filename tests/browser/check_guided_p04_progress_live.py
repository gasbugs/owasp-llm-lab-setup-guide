from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page()
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto('http://127.0.0.1:28097', wait_until='networkidle')
    waiting = []
    state = {'suite_id': None, 'phase': 'idle', 'total':27, 'cases':[]}
    page.route('**/api/test-progress/P04', lambda route: route.fulfill(json=state))
    page.route('**/api/practice/P04/verify', lambda route: waiting.append(route))
    page.evaluate('selectTab(1,"P04"); selectModelCallPane("grade")')
    page.locator('#h04-verify').click()
    expect(page.locator('#h04-verify')).to_be_disabled()
    state.update(suite_id='fresh-fixture',phase='running',current_case={'case_id':'first','status':'실행 중','started_at':__import__('time').time()-2})
    expect(page.locator('#case-progress-list .case-running-bar')).to_have_count(1)
    expect(page.locator('#case-progress-phase')).to_contain_text('0/27')
    state.update(phase='verifying',cases=[{'case_id':'first','case_verified':True}],current_case={'case_id':'second','status':'채점 중','started_at':__import__('time').time()})
    expect(page.locator('#case-progress-list .case-badge').first).to_have_text('PASS')
    expect(page.locator('#case-progress-list .case-running-bar')).to_have_count(1)
    state.update(cases=[{'case_id':'first','case_verified':True},{'case_id':'second','status':'ERR'}],current_case=None)
    expect(page.locator('#case-progress-list .case-card')).to_have_count(2)
    expect(page.locator('#case-progress-list .case-badge').nth(1)).to_have_text('ERR')
    expect(page.locator('#case-progress-phase')).to_contain_text('2/27')
    state.update(phase='finished',current_case=None)
    waiting.pop().fulfill(json={'activity_id':'P04','contract_version':'p04-guardrail-v1','task_completed':False,'security_verdict':'ERR','course_verdict':'ERR','result':{'cases':state['cases']},'reason':'browser fixture'})
    expect(page.locator('#case-progress-list .case-running-bar')).to_have_count(0)
    expect(page.locator('#h04-verify')).to_be_enabled()
    page.locator('#h04-verify').click()
    expect(page.locator('#case-progress-list .case-badge')).not_to_have_text(['PASS','ERR'])
    expect(page.locator('#case-progress-list .case-card')).to_have_count(0)
    state.update(suite_id='second-fixture',phase='running',cases=[],current_case={'case_id':'first','status':'실행 중','started_at':__import__('time').time()})
    expect(page.locator('#case-progress-list .case-running-bar')).to_have_count(1)
    state.update(phase='finished',current_case=None)
    waiting.pop().fulfill(json={'activity_id':'P04','contract_version':'p04-guardrail-v1','task_completed':False,'security_verdict':'ERR','course_verdict':'ERR','result':{'cases':[]}})
    expect(page.locator('#h04-verify')).to_be_enabled()
    assert not errors, errors
    print('PASS: P04 current-case bar, sequential verified results, stop after second ERR, 2/27 count, finish and regrade reset; browser fixtures only')
    browser.close()
